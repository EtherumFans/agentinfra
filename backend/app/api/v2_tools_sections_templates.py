    if not _can_manage_section(row, current_user):
        raise HTTPException(status_code=403, detail={"error": "section_forbidden"})
    await guided_section_repository.soft_delete(db, row)
    await log_action(
        db,
        str(current_user.id),
        current_user.username,
        "guided_section.delete",
        "guided_section",
        row.section_id,
        organization_id=str(current_org.id),
    )
    await db.commit()
    return Response(status_code=204)
