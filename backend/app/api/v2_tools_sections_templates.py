"""iCoDer ``GET /api/v2/tools/templates/`` + ``/sections/`` — Corti §13.4 LIST.

Cycle 4 (2026-07-01) — wire-shape parity for the read-only discovery path
that an SDK caller needs in order to find templates and sections to pass
to the cycle-3 generator endpoint.

Spec sources (ground truth, never inferred):
- ``docs/corti-reverse-engineered/guided-templates-list.md`` — operationId
  ``guided_templates_list``, path ``GET /documents/templates/``.
- ``docs/corti-reverse-engineered/guided-sections-list.md`` — operationId
  ``guided_sections_list``, path ``GET /documents/sections/``.

What this endpoint IS
---------------------
- A read-only LIST endpoint returning the Corti-shape template/section
  metadata envelope.

What this endpoint is NOT
--------------------------
- NOT a real CRUD surface. Cycle 4 ships stub data (one Corti-standard
  template + one user-created template; one Corti-standard section + one
  user-created section) to validate the wire contract. Full CRUD
  (create / update / delete / publish / version) lands in follow-on
  cycles once real storage is designed.
- NOT a replacement for the legacy M3-0 ``/api/templates`` surface.
  That DB-backed CRUD with iCoDer-Chinese category enums stays untouched
  in this cycle; cleaning it up is a separate Phase 2 task.

Filter handling
---------------
The spec accepts repeatable ``lang``, ``region``, ``specialty``, ``label``
query params, a ``published`` boolean, and a ``source`` enum. Cycle 4
accepts the params and applies a simple subset match (template is
included if **every** provided filter matches its stub data — empty
filter list ⇒ all entries returned). This is enough to exercise the
filter contract without overcommitting to a filter algorithm the real
DB layer will replace in a later cycle.
"""

