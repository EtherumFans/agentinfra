@router.post(
    "/sections/",
    response_model=GuidedSection,
    status_code=201,
)
@router.post(
    "/sections",
    response_model=GuidedSection,
    status_code=201,
)
async def create_v2_tools_section(
    body: GuidedSectionCreate,
    current_user: User = Depends(get_current_user),
    current_org: Organization = Depends(get_current_organization),
    db: AsyncSession = Depends(get_db),
) -> GuidedSection:
    """Create an encrypted tenant-owned section for the local Builder."""
    try:
        definition = _section_definition(
            name=body.name,
            description=body.description,
            specialties=body.specialties,
            labels=body.labels,
            output_schema=body.outputSchema,
        )
    except ValueError as exc:
        raise HTTPException(
            status_code=422,
            detail={"error": "invalid_output_schema", "reason": str(exc)},
        ) from exc
    row = await guided_section_repository.create(
        db,
        organization_id=str(current_org.id),
        owner_id=str(current_user.id),
        language=body.language,
        definition=definition,
        auto_generated=False,
        source="user",
    )
    await log_action(
        db,
        str(current_user.id),
        current_user.username,
        "guided_section.create",
        "guided_section",
        row.section_id,
        organization_id=str(current_org.id),
    )
    await db.commit()
    await db.refresh(row)
    return _stored_section_projection(row)


@router.get(
    "/sections/{section_id}",
    response_model=GuidedSection,
    status_code=200,
)
async def get_v2_tools_section(
    section_id: str,
    current_user: User = Depends(get_current_user),
    current_org: Organization = Depends(get_current_organization),
    db: AsyncSession = Depends(get_db),
) -> GuidedSection:
    """Get one curated or tenant-created section without invoking an LLM."""
    curated = next((section for section in _CURATED_SECTIONS if section.id == section_id), None)
    if curated is not None:
        return _curated_section_projection(curated)
    stored = await guided_section_repository.list(
        db, organization_id=str(current_org.id)
    )
    row = next((item for item in stored if item.section_id == section_id), None)
    if row is None:
        raise HTTPException(
            status_code=404,
            detail={"error": "section_not_found", "sectionId": section_id},
        )
    return _stored_section_projection(row)


@router.patch(
    "/sections/{section_id}",
    response_model=GuidedSection,
    status_code=200,
)
async def update_v2_tools_section(
    section_id: str,
    body: GuidedSectionUpdate,
    current_user: User = Depends(get_current_user),
    current_org: Organization = Depends(get_current_organization),
    db: AsyncSession = Depends(get_db),
) -> GuidedSection:
    if any(section.id == section_id for section in _CURATED_SECTIONS):
        raise HTTPException(
            status_code=403,
            detail={"error": "section_builtin_protected", "sectionId": section_id},
        )
    row = await guided_section_repository.get(
        db, organization_id=str(current_org.id), section_id=section_id
    )
    if row is None:
        raise HTTPException(
            status_code=404,
            detail={"error": "section_not_found", "sectionId": section_id},
        )
    if not _can_manage_section(row, current_user):
        raise HTTPException(status_code=403, detail={"error": "section_forbidden"})
    current = guided_section_repository.definition(row)
    changes = body.model_dump(exclude_unset=True)
    instructions = current.get("instructions", {})
    current_description = (
        instructions.get("contentPrompt", "") if isinstance(instructions, dict) else ""
    )
    try:
        definition = _section_definition(
            name=changes.get("name", row.name),
            description=changes.get("description", current_description),
            specialties=changes.get("specialties", current.get("specialties", ["custom"])),
            labels=[
                item if isinstance(item, GuidedLabel) else GuidedLabel(**item)
                for item in changes.get("labels", current.get("labels", []))
            ],
            output_schema=changes.get("outputSchema", current.get("outputSchema", {"type": "string"})),
        )
    except (ValueError, TypeError) as exc:
        raise HTTPException(
            status_code=422,
            detail={"error": "invalid_section", "reason": str(exc)},
        ) from exc
    await guided_section_repository.update(
        db,
        row,
        language=changes.get("language", row.language),
        definition=definition,
    )
    await log_action(
        db,
        str(current_user.id),
        current_user.username,
        "guided_section.update",
        "guided_section",
        row.section_id,
        organization_id=str(current_org.id),
    )
    await db.commit()
    await db.refresh(row)
    return _stored_section_projection(row)


