@router.get(
    "/templates/",
    response_model=List[GuidedTemplate],
    response_model_exclude_none=True,
    status_code=200,
)
@router.get(
    "/templates",
    response_model=List[GuidedTemplate],
    response_model_exclude_none=True,
    status_code=200,
)
async def list_v2_tools_templates(
    lang: List[str] = Query(default_factory=list, description="BCP 47 language tag filter; repeatable"),
    region: List[str] = Query(default_factory=list, description="ISO 3166-1 alpha-3 region code filter; repeatable"),
    specialty: List[str] = Query(default_factory=list, description="Clinical specialty filter; repeatable"),
    label: List[str] = Query(default_factory=list, description="Filter as `key:value`; repeatable"),
    published: Optional[bool] = Query(default=None, description="true=published only, false=unpublished only, omit=both"),
    source: Optional[Literal["user", "corti", "project"]] = Query(default=None, description="Content source filter"),
    current_user: User = Depends(get_current_user),
    current_org: Organization = Depends(get_current_organization),
    db: AsyncSession = Depends(get_db),
) -> List[GuidedTemplate]:
    """List authenticated tenant templates in Corti's discovery shape."""
    rows = list((await db.scalars(
        select(Template).where(
            Template.organization_id == current_org.id,
            Template.deleted_at.is_(None),
        )
        .order_by(Template.is_builtin.desc(), Template.created_at.desc())
    )).all())
    latest_versions: dict[str, TemplateVersion] = {}
    if rows:
        versions = list((await db.scalars(
            select(TemplateVersion).where(
                TemplateVersion.organization_id == current_org.id,
                TemplateVersion.template_id.in_([row.id for row in rows]),
            ).order_by(TemplateVersion.version_number.desc())
        )).all())
        for version in versions:
            latest_versions.setdefault(version.template_id, version)
    templates = [
        _template_projection(row, latest_versions.get(row.id)) for row in rows
    ]
    return [GuidedTemplate(**d) for d in _apply_filters(
        templates, lang=lang, region=region, specialty=specialty,
        label=label, published=published, source=source,
    )]


@router.get(
    "/templates/{template_id}",
    response_model=GuidedTemplate,
    response_model_exclude_none=True,
    status_code=200,
)
async def get_v2_tools_template(
    template_id: str,
    current_user: User = Depends(get_current_user),
    current_org: Organization = Depends(get_current_organization),
    db: AsyncSession = Depends(get_db),
) -> GuidedTemplate:
    """Get one opaque public template within the authenticated tenant."""
    row = await resolve_public_template(
        db,
        organization_id=str(current_org.id),
        template_id=template_id,
    )
    if row is None:
        raise HTTPException(
            status_code=404,
            detail={"error": "template_not_found", "templateId": template_id},
        )
    version = (await db.scalars(
        select(TemplateVersion).where(
            TemplateVersion.organization_id == current_org.id,
            TemplateVersion.template_id == row.id,
        ).order_by(TemplateVersion.version_number.desc()).limit(1)
    )).first()
    return _template_projection(row, version)


@router.post(
    "/templates/{template_id}/publish",
    response_model=GuidedTemplateVersion,
    status_code=201,
)
async def publish_v2_tools_template(
    template_id: str,
    current_user: User = Depends(get_current_user),
    current_org: Organization = Depends(get_current_organization),
    db: AsyncSession = Depends(get_db),
) -> GuidedTemplateVersion:
    """iCoDer extension: publish a public-ID template as an immutable version."""
    row = await resolve_public_template(
        db,
        organization_id=str(current_org.id),
        template_id=template_id,
    )
    if row is None:
        raise HTTPException(
            status_code=404,
            detail={"error": "template_not_found", "templateId": template_id},
        )
    published = await publish_template(
        template_id=row.id,
        user=current_user,
        current_org=current_org,
        db=db,
    )
    return GuidedTemplateVersion(
        id=published.id,
        versionNumber=published.version_number,
        generation=published.generation,
        deletedAt=None,
    )


