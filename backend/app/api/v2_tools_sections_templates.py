@router.get(
    "/templates/",
    response_model=List[GuidedTemplate],
    status_code=200,
)
@router.get(
    "/templates",
    response_model=List[GuidedTemplate],
    status_code=200,
)
async def list_v2_tools_templates(
    lang: List[str] = Query(default_factory=list, description="BCP 47 language tag filter; repeatable"),
    region: List[str] = Query(default_factory=list, description="ISO 3166-1 alpha-3 region code filter; repeatable"),
    specialty: List[str] = Query(default_factory=list, description="Clinical specialty filter; repeatable"),
    label: List[str] = Query(default_factory=list, description="Filter as `key:value`; repeatable"),
    published: Optional[bool] = Query(default=None, description="true=published only, false=unpublished only, omit=both"),
    source: Optional[Literal["user", "corti"]] = Query(default=None, description="Content source filter"),
    current_user: User = Depends(get_current_user),
) -> List[GuidedTemplate]:
    """Corti §13.4 Guided Templates — ``GET /documents/templates/`` (Cycle 4 stub)."""
    # Hospital-pilot gate (REST parity with cycles 1-3)
    if not os.environ.get("ICODER_CREDENTIAL_LLM", "").strip():
        if os.environ.get("ICODER_ALLOW_DEGRADED_NO_KEY", "") != "1":
            raise HTTPException(
                status_code=503,
                detail={
                    "requestid": str(uuid.uuid4()),
                    "status": 503,
                    "type": "service_unavailable",
                    "detail": "ICODER_CREDENTIAL_LLM not set; hospital-pilot gate refuses to serve.",
                },
            )
    return [GuidedTemplate(**d) for d in _apply_filters(
        _STUB_TEMPLATES, lang=lang, region=region, specialty=specialty,
        label=label, published=published, source=source,
    )]


