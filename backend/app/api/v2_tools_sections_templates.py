def _template_projection(
    row: Template,
    version: TemplateVersion | None = None,
) -> GuidedTemplate:
    """Project a tenant Template row to Corti's discovery shape."""
    language = row.language.value if hasattr(row.language, "value") else str(row.language)
    category = row.category.value if hasattr(row.category, "value") else str(row.category)
    created_at = row.created_at or row.updated_at
    updated_at = row.updated_at or created_at
    definition = template_definition(row)
    inherited_from_id = (
        definition.get("inheritedFromId") if definition else None
    )
    auto_generated = bool(
        definition and ("sections" in definition or inherited_from_id)
    )
    published_version = None
    if version is not None:
        import json
        published_version = GuidedTemplateVersion(
            id=version.id,
            versionNumber=version.version_number,
            generation=json.loads(version.generation_json),
            deletedAt=None,
        )
    elif row.is_builtin:
        published_version = GuidedTemplateVersion(
            id=public_template_version_id(row),
            versionNumber=0,
            generation=template_generation(row),
            deletedAt=None,
        )
    return GuidedTemplate(
        id=public_template_id(row),
        inheritedFromId=inherited_from_id,
        autoGenerated=auto_generated,
        source="corti" if row.is_builtin else "user",
        name=row.name,
        description=row.description or "",
        languages=[language],
        regions=["CHN" if language == "zh-CN" else "USA"],
        specialties=[category],
        labels=[GuidedLabel(key="category", value=category)],
        publishedVersion=published_version,
        createdBy=None,
        createdAt=(created_at.isoformat() if created_at else _now_iso()),
        updatedAt=(updated_at.isoformat() if updated_at else _now_iso()),
        deletedAt=None,
    )


def _stored_section_projection(row) -> GuidedSection:
    definition = guided_section_repository.definition(row)
    instructions = definition.get("instructions", {})
    description = instructions.get("contentPrompt") if isinstance(instructions, dict) else None
    raw_labels = definition.get("labels", [])
    labels = [GuidedLabel(**item) for item in raw_labels if isinstance(item, dict)]
    return GuidedSection(
        id=row.section_id,
        inheritedFromId=definition.get("inheritedFromId"),
        autoGenerated=row.auto_generated,
        versionId=row.version_id,
        generation=definition,
        source=row.source if row.source in {"user", "corti", "project"} else "project",
        name=row.name,
        languages=[row.language],
        regions=["CHN" if row.language.casefold().startswith("zh") else "USA"],
        specialties=definition.get("specialties", ["custom"]),
        description=description,
        labels=labels or [GuidedLabel(key="resource_type", value="dynamic-section")],
        createdBy=row.owner_id,
        createdAt=row.created_at.isoformat(),
        updatedAt=row.updated_at.isoformat(),
        deletedAt=row.deleted_at.isoformat() if row.deleted_at else None,
    )


def _curated_section_projection(section: GuidedSection) -> GuidedSection:
    definition = resolve_curated_section(section.id)
    return section.model_copy(update={
        "versionId": definition.get("sectionVersionId") if definition else None,
        "generation": definition,
    })


def _validate_section_output_schema(node: Any, path: str = "outputSchema") -> None:
    if not isinstance(node, dict):
        raise ValueError(f"{path} must be an object")
    node_type = node.get("type")
    if node_type not in {"string", "number", "boolean", "array", "object"}:
        raise ValueError(f"{path}.type is unsupported")
    if node_type == "array":
        if "items" not in node:
            raise ValueError(f"{path}.items is required")
        _validate_section_output_schema(node["items"], f"{path}.items")
    if node_type == "object":
        seen: set[str] = set()
        for index, field in enumerate(node.get("fields", [])):
            key = str(field.get("key", "")).strip() if isinstance(field, dict) else ""
            if not key:
                raise ValueError(f"{path}.fields[{index}].key is required")
            if key in seen:
                raise ValueError(f"{path}.fields contains duplicate key {key}")
            seen.add(key)
            _validate_section_output_schema(field.get("value"), f"{path}.fields[{index}].value")


def _section_definition(
    *,
    name: str,
    description: str,
    specialties: list[str],
    labels: list[GuidedLabel],
    output_schema: dict[str, Any],
) -> dict[str, Any]:
    _validate_section_output_schema(output_schema)
    return {
        "heading": name,
        "instructions": {
            "contentPrompt": description or "Generate only content supported by the source context."
        },
        "outputSchema": output_schema,
        "specialties": specialties or ["custom"],
        "labels": [item.model_dump(mode="json") for item in labels],
    }


def _can_manage_section(row, current_user: User) -> bool:
    role = getattr(getattr(current_user, "role", None), "value", getattr(current_user, "role", None))
    return row.owner_id == str(current_user.id) or role == "admin"


# ─── Filter helpers ─────────────────────────────────────────────────


def _apply_filters(
    items: List[dict],
    *,
    lang: List[str],
    region: List[str],
    specialty: List[str],
    label: List[str],
    published: Optional[bool],
    source: Optional[Literal["user", "corti", "project"]],
) -> List[dict]:
    """Subset filter — every provided filter must match (AND across categories,
    OR within a category).

    Empty filter list ⇒ all items pass. Soft-deleted items are excluded
    unless the caller opts in via a future ``includeDeleted`` flag
    (intentionally NOT supported in Cycle 4 — ``published=false`` is the
    only "non-published" notion surfaced by the spec, not "deleted").
    """
    out: List[dict] = []
    for it in items:
        d = it.model_dump(mode="json") if hasattr(it, "model_dump") else dict(it)
        # Soft-delete exclusion
        if d.get("deletedAt"):
            continue
        if lang and not (set(lang) & set(d.get("languages", []))):
            continue
        if region and not (set(region) & set(d.get("regions", []))):
            continue
        if specialty and not (set(specialty) & set(d.get("specialties", []))):
            continue
        if label:
            kv_set = {f"{lab['key']}:{lab['value']}" for lab in d.get("labels", [])}
            if not (set(label) & kv_set):
                continue
        if source is not None and d.get("source") != source:
            continue
        # The current catalog has no publishedVersion; treat all entries as
        # implicitly "published=true" (existence implies a version).
        # published=false ⇒ empty result (no unpublished rows exposed yet).
        is_published = d.get("publishedVersion") is not None
        if published is not None and is_published is not published:
            continue
        out.append(d)
    return out


